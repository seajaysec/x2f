"""Render a TrueType font into runtime/x2f_font.h: printable ASCII at a few pixel sizes, as 4-bit coverage, for the
packs' text (open-field's op1f_paint_mask paints coverage in any colour). A developer step, not run by x2f:

    uv run --no-project --with pillow python tools/make_font.py FONT.ttf

The font shipped is Perun Light (SIL Open Font License 1.1, runtime/font/OFL.txt)."""
import os, sys
from PIL import ImageFont, Image, ImageDraw

SIZES = (11, 14, 18)              # pixel sizes: labels, small values, header values and large panel text
font_path = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "runtime", "x2f_font.h")
lines = ["// Generated by tools/make_font.py from %s. Do not edit." % os.path.basename(font_path),
         "// Perun, SIL Open Font License 1.1 (runtime/font/OFL.txt): glyphs rendered as 4-bit coverage.",
         "#pragma once", "#include <stdint.h>", "namespace x2f_font {",
         "struct Glyph { uint32_t at; uint8_t w, h; int8_t left, top; uint8_t advance; };",
         "struct Face { uint8_t size, ascent; const Glyph* glyphs; const uint8_t* bits; };"]
faces = []
for size in SIZES:
    f = ImageFont.truetype(font_path, size)
    ascent, _ = f.getmetrics()
    glyphs, bits = [], []
    for code in range(32, 127):
        ch = chr(code)
        l, t, r, b = f.getbbox(ch)
        w, h = max(0, r - l), max(0, b - t)
        adv = int(round(f.getlength(ch)))
        at = len(bits)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255)
            px = list(im.get_flattened_data()) if hasattr(im, "get_flattened_data") else list(im.getdata())
            for i in range(0, len(px), 2):
                a = px[i] >> 4
                c = (px[i + 1] >> 4) if i + 1 < len(px) else 0
                bits.append(a | (c << 4))
        glyphs.append("{%d, %d, %d, %d, %d, %d}" % (at, w, h, l, t - ascent, adv))   # top: from the baseline
    lines.append("const Glyph glyphs_%d[95] = { %s };" % (size, ", ".join(glyphs)))
    lines.append("const uint8_t bits_%d[%d] = { %s };" % (size, max(1, len(bits)), ", ".join(str(b) for b in bits) or "0"))
    faces.append("{%d, %d, glyphs_%d, bits_%d}" % (size, ascent, size, size))
    print("size %d: %d bytes of coverage" % (size, len(bits)))
lines.append("const Face faces[%d] = { %s };" % (len(SIZES), ", ".join(faces)))
lines.append("}")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out)
